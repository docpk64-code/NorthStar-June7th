import assert from 'node:assert/strict';
import { generate, isEnabled, promptFor, validateInput, CONSENT_VERSION, MAX_BODY } from '../netlify/server/smile-core.mjs';
import status from '../netlify/functions/smile-status.mjs';
const env = { OPENAI_API_KEY: 'test-only-secret', SMILE_AI_ENABLED: 'true', SMILE_AI_PRIVACY_READY: 'true' };
const image = Buffer.concat([Buffer.from([255, 216, 255]), Buffer.alloc(200)]).toString('base64');
const input = { treatment: 'arch', consent: true, consentVersion: CONSENT_VERSION, image: `data:image/jpeg;base64,${image}` };
const request = (body = input, origin = 'https://northstarimplants.com') => new Request('https://northstarimplants.com/.netlify/functions/smile-generate', { method: 'POST', headers: { origin, 'content-type': 'application/json' }, body: JSON.stringify(body) });
let calls = 0;
const fetcher = async (url, options) => {
  calls++; assert.equal(url, 'https://api.openai.com/v1/images/edits');
  const body = JSON.parse(options.body);
  assert.equal(options.headers.Authorization, 'Bearer test-only-secret');
  assert.equal(body.model, 'gpt-image-1.5'); assert.equal(body.input_fidelity, 'high'); assert.equal(body.n, 1);
  assert.equal(body.images[0].image_url, input.image); assert(!('user' in body));
  assert(body.prompt.includes('implant-supported'));
  return Response.json({ data: [{ b64_json: image }] });
};
assert(!isEnabled({})); assert(!isEnabled({ ...env, SMILE_AI_PRIVACY_READY: 'false' }));
assert.equal((await generate(request(), { env: {}, fetcher })).status, 503); assert.equal(calls, 0);
assert.equal((await generate(request(input, 'https://other.example'), { env, fetcher })).status, 403); assert.equal(calls, 0);
assert.equal((await generate(request({ ...input, consent: false }), { env, fetcher })).status, 400);
assert.equal((await generate(request({ ...input, consentVersion: 'old' }), { env, fetcher })).status, 400);
assert.equal((await generate(request({ ...input, treatment: 'toString' }), { env, fetcher })).status, 400);
assert.equal((await generate(request({ ...input, image: 'https://arbitrary.example/image.jpg' }), { env, fetcher })).status, 400);
assert(validateInput({ ...input, image: 'data:image/jpeg;base64,' + Buffer.alloc(200).toString('base64') }));
const tooLarge = request({ ...input, image: 'x'.repeat(MAX_BODY) });
assert.equal((await generate(tooLarge, { env, fetcher })).status, 413); assert.equal(calls, 0);
const response = await generate(request(), { env, fetcher });
assert.equal(response.status, 200); assert.equal(response.headers.get('cache-control'), 'no-store, private');
const result = await response.json(); assert.equal(result.image, input.image); assert.equal(result.treatment, 'arch'); assert.equal(calls, 1);
const denied = await generate(request(), { env, fetcher: async () => Response.json({ error: { message: 'test-only-secret and private upstream content' } }, { status: 401 }) });
assert.equal(denied.status, 502); assert(!(await denied.text()).includes('test-only-secret'));
assert(promptFor('aligners').includes('Do not whiten')); assert(promptFor('veneers').includes('Preserve tooth positions'));
assert(!(await (await status(new Request('https://northstarimplants.com/.netlify/functions/smile-status'))).text()).includes('OPENAI_API_KEY'));
console.log('PASS: activation gates, consent, origin, treatment allowlist, image validation, size limits, server-only key, treatment prompts, noncached result and sanitized provider errors. No live API calls.');
