import assert from 'node:assert/strict';
import React, { act } from 'react';
import { JSDOM } from 'jsdom';
const dom = new JSDOM('<div id="root"></div>', { url: 'https://northstarimplants.com/smile-preview/' });
Object.assign(globalThis, { window: dom.window, document: dom.window.document, React, IS_REACT_ACT_ENVIRONMENT: true });
Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
Object.defineProperty(dom.window.HTMLVideoElement.prototype, 'videoWidth', { get: () => 1280 });
Object.defineProperty(dom.window.HTMLVideoElement.prototype, 'videoHeight', { get: () => 720 });
dom.window.HTMLVideoElement.prototype.play = async () => {};
dom.window.HTMLCanvasElement.prototype.getContext = (() => ({ drawImage() {} })) as any;
dom.window.HTMLCanvasElement.prototype.toBlob = callback => callback(new Blob(['photo'], { type: 'image/jpeg' }) as any);
const { createRoot } = await import('react-dom/client');
const { default: Camera } = await import('../src/components/SmileCamera');
let stopCount = 0, closed = 0; let captured: File | undefined; let constraints: MediaStreamConstraints | undefined;
const makeStream = () => ({ getTracks: () => [{ stop() { stopCount++; } }] }) as any;
let getMedia = async (options: MediaStreamConstraints) => { constraints = options; return makeStream(); };
Object.defineProperty(navigator, 'mediaDevices', { value: { getUserMedia: (options: MediaStreamConstraints) => getMedia(options) }, configurable: true });
const root = createRoot(document.getElementById('root')!);
const render = async (key: string) => act(async () => { root.render(<Camera key={key} onCapture={file => { captured = file; }} onClose={() => { closed++; }} />); });
const button = (name: string) => [...document.querySelectorAll('button')].find(button => button.textContent === name)!;
await render('capture');
assert.equal(constraints?.audio, false); assert.equal((constraints?.video as MediaTrackConstraints).facingMode && ((constraints?.video as any).facingMode.ideal), 'user');
await act(async () => button('Capture my smile').click());
assert.equal(captured?.type, 'image/jpeg'); assert.equal(closed, 1); assert.equal(stopCount, 1);
await render('visibility');
Object.defineProperty(document, 'hidden', { get: () => true, configurable: true });
await act(async () => document.dispatchEvent(new dom.window.Event('visibilitychange')));
assert.equal(stopCount, 2); assert(document.querySelector('[role=status]')?.textContent?.includes('paused'));
getMedia = async () => { throw new DOMException('Permission denied', 'NotAllowedError'); };
await render('denied');
assert(document.querySelector('[role=status]')?.textContent?.includes('not allowed')); assert(button('Try camera again'));
let resolve!: (value: MediaStream) => void;
getMedia = () => new Promise<MediaStream>(r => { resolve = r; });
await render('late-permission');
await act(async () => root.unmount());
await act(async () => resolve(makeStream()));
assert.equal(stopCount, 3, 'A late permission result must stop its stream after unmount');
dom.window.close();
console.log('PASS: front-camera preference, no microphone, JPEG capture, stream cleanup, hidden-page stop, denied permission, late permission after unmount.');
