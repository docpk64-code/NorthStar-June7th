import assert from 'node:assert/strict';
import React,{act} from 'react';
import {JSDOM} from 'jsdom';
const dom=new JSDOM('<div id="root"></div>',{url:'https://northstarimplants.com/patient-forms/new-patient/'});
Object.assign(globalThis,{React,window:dom.window,document:dom.window.document,IS_REACT_ACT_ENVIRONMENT:true,requestAnimationFrame:(fn:()=>void)=>{fn();return 0;}});
Object.defineProperty(globalThis,'navigator',{value:dom.window.navigator,configurable:true});
globalThis.IntersectionObserver=class {observe(){} disconnect(){} unobserve(){}} as any;
const {createRoot}=await import('react-dom/client');
const {default:Page}=await import('../src/IntakePage');
const root=createRoot(document.getElementById('root')!);
await act(async()=>root.render(<Page/>));
const click=async(el:Element)=>act(async()=>(el as HTMLElement).click());
const input=async(id:string,value:string)=>act(async()=>{const el=document.getElementById(id) as HTMLInputElement;Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype,'value')!.set!.call(el,value);el.dispatchEvent(new window.Event('input',{bubbles:true}));});
const radio=(id:string,value:string)=>document.querySelector(`input[name="intake-${id}"][value="${value}"]`)!;
const buttons=()=>Array.from(document.querySelectorAll('button'));
const section=(n:number)=>document.querySelectorAll('.intake-steps button')[n];
await input('intake-first_name','Example');
assert.equal(document.querySelector('#intake-first_name + .intake-answer')?.textContent,'Example');
await click(buttons().find(b=>b.textContent==='Continue →')!);
assert(document.querySelector('[role=status]')!.textContent!.includes('required'));
assert.equal(document.querySelector('.intake-section[data-active=true]')?.getAttribute('aria-label'),'Patient information');
await click(section(3));await click(radio('health_0','Yes'));assert(!document.getElementById('intake-health_0-detail'));
await click(radio('health_0','No'));assert(!(radio('health_0','Yes') as HTMLInputElement).checked);assert(document.getElementById('intake-health_0-detail'));
await click(section(2));
const symptom=(v:string)=>document.querySelector(`input[name="intake-dental_symptoms"][value="${v}"]`)!;
await click(symptom('Bleeding gums'));await click(symptom('None of these'));assert(!(symptom('Bleeding gums') as HTMLInputElement).checked);
await click(symptom('Loose teeth'));assert(!(symptom('None of these') as HTMLInputElement).checked);
await click(section(4));await click(radio('takes_medicines','Yes'));assert.equal(document.querySelectorAll('.intake-medicine').length,1);
await click(buttons().find(b=>b.textContent==='+ Add another medicine')!);assert.equal(document.querySelectorAll('.intake-medicine').length,2);
await click(buttons().find(b=>b.textContent==='Remove medicine 2')!);assert.equal(document.querySelectorAll('.intake-medicine').length,1);
await click(radio('allergy_status','Yes'));assert(document.getElementById('intake-allergy_details'));
await click(radio('allergy_status','No known allergies'));assert(!document.getElementById('intake-allergy_details'));
await click(section(6));assert(document.querySelector('.intake-review details li'));
let printed=false;window.print=()=>{printed=true;};window.confirm=()=>false;
await click(buttons().find(b=>b.textContent==='Print / Save completed form')!);assert(!printed);
window.confirm=()=>true;await click(buttons().find(b=>b.textContent==='Print / Save completed form')!);assert(printed);
assert(document.querySelector('.intake-print-heading')?.textContent?.includes('INCOMPLETE'));
assert.equal(document.querySelectorAll('button[type=submit]').length,0);assert.equal(window.localStorage.length,0);
await click(buttons().find(b=>b.textContent==='Clear answers')!);assert.equal((document.getElementById('intake-first_name') as HTMLInputElement).value,'');
assert.equal(document.querySelectorAll('.intake-section').length,7);
await act(async()=>root.unmount());
console.log('PASS: radio exclusivity, conditional details, exclusive checklist choices, repeatable medicines, required-answer review, incomplete-print confirmation, printable answers, clear, and no submission/storage.');
